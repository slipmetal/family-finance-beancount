"""Короткое имя для того, что не помещается в кнопку.

В `callback_data` у Telegram 64 байта на всё. Одно только `Assets:Ameria:Card0001`
занимает 22, имя файла — ещё сорок, и вместе они не влезают.

Держать вместо них номер в словаре нельзя, и причина не в аккуратности:
машина на fly засыпает, когда её ни о чём не спрашивают, а между сообщением
с кнопками и нажатием человек вполне может отвлечься на час. Словарь до
нажатия не доживёт, и кнопки перестанут работать именно тогда, когда ими
наконец решили воспользоваться.

Поэтому ключ считается, а не запоминается. На нажатии inbox перечитывается
заново, и ключ ищется среди того, что там есть на самом деле. Заодно это
снимает вопрос обхода каталога: имя файла в кнопку не кладётся вовсе, и
обратно приехать ему неоткуда.
"""

from __future__ import annotations

import hashlib
from collections.abc import Callable, Iterable
from typing import TypeVar

T = TypeVar("T")

#: Байт в ключе. Шесть — это двенадцать шестнадцатеричных символов и 48 бит:
#: на десяток файлов в inbox совпадений не бывает, а в кнопку влезает с запасом.
SIZE = 6

#: Значение «ничего из перечисленного»: у кнопки «пропустить» нет предмета.
NOTHING = "-"


def of(text: str) -> str:
    """Ключ для строки. Одна и та же строка даёт один и тот же ключ всегда."""
    return hashlib.blake2s(text.encode("utf-8"), digest_size=SIZE).hexdigest()


def find(items: Iterable[T], name: Callable[[T], str], key: str) -> T | None:
    """Единственный элемент с таким ключом.

    Ноль совпадений — файл унесли или счёт переименовали, пока сообщение
    висело в чате. Два — редчайшее совпадение хешей. В обоих случаях None:
    угадывать, что человек имел в виду, тут нечего.
    """
    if key == NOTHING:
        return None
    found = [item for item in items if of(name(item)) == key]
    return found[0] if len(found) == 1 else None
